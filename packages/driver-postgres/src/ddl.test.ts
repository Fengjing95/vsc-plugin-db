import { describe, expect, it } from 'vitest';
import { DriverError } from '@db-explorer/core';
import type { TableSpec } from '@db-explorer/core';
import {
  buildCreateSchemaStatements,
  buildCreateTableStatements,
  buildAlterTableStatements,
  buildDropSchemaStatements,
  escapeDdlLiteral,
} from './ddl';

function baseSpec(overrides: Partial<TableSpec> = {}): TableSpec {
  return {
    name: 'users',
    comment: '用户表',
    columns: [
      { name: 'id', dataType: 'bigint', nullable: false, isPrimaryKey: true, autoIncrement: true, ordinal: 1 },
      { name: 'uname', dataType: 'varchar(64)', nullable: false, isPrimaryKey: false, defaultValue: 'anon', comment: '名称', ordinal: 2 },
      { name: 'amount', dataType: 'int', nullable: true, isPrimaryKey: false, ordinal: 3 },
    ],
    ...overrides,
  };
}

describe('buildCreateTableStatements（M8-PG）', () => {
  it('生成 CREATE TABLE：双引号限定、IDENTITY 自增、NOT NULL/DEFAULT、主键；注释走独立 COMMENT ON', () => {
    const stmts = buildCreateTableStatements('public', baseSpec());
    expect(stmts[0].destructive).toBeUndefined();
    expect(stmts[0].sql).toBe(
      [
        'CREATE TABLE "public"."users" (',
        '  "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,',
        '  "uname" varchar(64) NOT NULL DEFAULT \'anon\',',
        '  "amount" int NULL,',
        '  PRIMARY KEY ("id")',
        ')',
      ].join('\n'),
    );
    expect(stmts.slice(1)).toEqual([
      { sql: 'COMMENT ON TABLE "public"."users" IS \'用户表\'' },
      { sql: 'COMMENT ON COLUMN "public"."users"."uname" IS \'名称\'' },
    ]);
  });

  it('无注释：仅 CREATE TABLE 一条', () => {
    const spec = baseSpec({ comment: undefined, columns: baseSpec().columns.map((c) => ({ ...c, comment: undefined })) });
    expect(buildCreateTableStatements('app', spec)).toHaveLength(1);
  });

  it('字面量转义：数值与 CURRENT_TIMESTAMP/CURRENT_DATE 原样，字符串引号翻倍；控制字符拒绝', () => {
    expect(escapeDdlLiteral('0')).toBe('0');
    expect(escapeDdlLiteral('current_timestamp')).toBe('current_timestamp');
    expect(escapeDdlLiteral('CURRENT_DATE')).toBe('CURRENT_DATE');
    expect(escapeDdlLiteral("it's")).toBe("'it''s'");
    expect(() => escapeDdlLiteral('a\nb')).toThrow(DriverError);
  });

  it('标识符校验（危险字符黑名单）：双引号/控制字符拒绝；连字符等真实合法名放行', () => {
    expect(() => buildCreateTableStatements('public', baseSpec({ name: 'x"y' }))).toThrow(DriverError);
    expect(() => buildCreateTableStatements('public', baseSpec({ name: 'x\ny' }))).toThrow(DriverError);
    // 分号/连字符由双引号双写转义安全承载（回归：test-api 类真实库名曾被白名单误拒）
    const stmts = buildCreateTableStatements('test-api', baseSpec({ name: 'cf-ddl_t;--x' }));
    expect(stmts[0].sql).toContain('"test-api"."cf-ddl_t;--x"');
  });
});

describe('buildAlterTableStatements（M8-PG）', () => {
  it('加列：非 destructive', () => {
    const current = baseSpec();
    const target: TableSpec = {
      ...current,
      columns: [...current.columns, { name: 'extra', dataType: 'varchar(32)', nullable: true, isPrimaryKey: false, ordinal: 4 }],
    };
    const stmts = buildAlterTableStatements('public', 'users', target, current);
    expect(stmts.map((s) => s.sql)).toEqual([
      'ALTER TABLE "public"."users" ADD COLUMN "extra" varchar(32) NULL',
    ]);
    expect(stmts.every((s) => !s.destructive)).toBe(true);
  });

  it('删列：destructive', () => {
    const current = baseSpec();
    const target: TableSpec = { ...current, columns: current.columns.slice(0, 2) };
    const stmts = buildAlterTableStatements('public', 'users', target, current);
    expect(stmts).toEqual([
      { sql: 'ALTER TABLE "public"."users" DROP COLUMN "amount"', destructive: true },
    ]);
  });

  it('改类型：ALTER COLUMN TYPE USING + destructive；仅改默认值：SET DEFAULT 非 destructive', () => {
    const current = baseSpec();
    const typeChange: TableSpec = {
      ...current,
      columns: current.columns.map((c) => (c.name === 'amount' ? { ...c, dataType: 'bigint' } : c)),
    };
    expect(buildAlterTableStatements('public', 'users', typeChange, current)).toEqual([
      {
        sql: 'ALTER TABLE "public"."users" ALTER COLUMN "amount" TYPE bigint USING "amount"::bigint',
        destructive: true,
      },
    ]);
    const defaultValueChange: TableSpec = {
      ...current,
      columns: current.columns.map((c) => (c.name === 'amount' ? { ...c, defaultValue: '0' } : c)),
    };
    expect(buildAlterTableStatements('public', 'users', defaultValueChange, current)).toEqual([
      { sql: 'ALTER TABLE "public"."users" ALTER COLUMN "amount" SET DEFAULT 0' },
    ]);
  });

  it('主键变更：先 DROP CONSTRAINT（destructive）→ ADD PRIMARY KEY（基线列已 NOT NULL，无需 SET）', () => {
    const current = baseSpec();
    const target: TableSpec = {
      ...current,
      columns: current.columns.map((c) => (c.name === 'uname' ? { ...c, nullable: false, isPrimaryKey: true } : c)),
    };
    const stmts = buildAlterTableStatements('public', 'users', target, current);
    expect(stmts.map((s) => s.sql)).toEqual([
      'ALTER TABLE "public"."users" DROP CONSTRAINT IF EXISTS "users_pkey"',
      'ALTER TABLE "public"."users" ADD PRIMARY KEY ("id", "uname")',
    ]);
    expect(stmts[0].destructive).toBe(true);
    expect(stmts[1].destructive).toBeUndefined();
  });

  it('主键变更含可空列：先 SET NOT NULL 再重建约束（PG ADD PRIMARY KEY 要求 NOT NULL）', () => {
    const current = baseSpec();
    const nullableUname: TableSpec = {
      ...current,
      columns: current.columns.map((c) => (c.name === 'uname' ? { ...c, nullable: true } : c)),
    };
    const target: TableSpec = {
      ...nullableUname,
      columns: nullableUname.columns.map((c) => (c.name === 'uname' ? { ...c, nullable: false, isPrimaryKey: true } : c)),
    };
    const stmts = buildAlterTableStatements('public', 'users', target, nullableUname);
    expect(stmts.map((s) => s.sql)).toEqual([
      'ALTER TABLE "public"."users" ALTER COLUMN "uname" SET NOT NULL',
      'ALTER TABLE "public"."users" DROP CONSTRAINT IF EXISTS "users_pkey"',
      'ALTER TABLE "public"."users" ADD PRIMARY KEY ("id", "uname")',
    ]);
    expect(stmts[0].destructive).toBeUndefined();
    expect(stmts[1].destructive).toBe(true);
  });

  it('表重命名：RENAME TO 首条语句（PG 不带 schema 目标），后续变更用新名', () => {
    const current = baseSpec();
    const target: TableSpec = { ...current, name: 'users_new', columns: current.columns.slice(0, 2) };
    const stmts = buildAlterTableStatements('public', 'users', target, current);
    expect(stmts[0].sql).toBe('ALTER TABLE "public"."users" RENAME TO "users_new"');
    expect(stmts[1].sql).toContain('"public"."users_new" DROP COLUMN');
  });

  it('无结构差异返回空数组', () => {
    const current = baseSpec();
    expect(buildAlterTableStatements('public', 'users', current, current)).toEqual([]);
  });

  it('删主键列：先 DROP CONSTRAINT 再 DROP COLUMN（PG 依赖约束顺序，D-15 定稿）', () => {
    const current = baseSpec();
    const target: TableSpec = { ...current, columns: current.columns.slice(1) };
    const stmts = buildAlterTableStatements('public', 'users', target, current);
    expect(stmts.map((s) => s.sql)).toEqual([
      'ALTER TABLE "public"."users" DROP CONSTRAINT IF EXISTS "users_pkey"',
      'ALTER TABLE "public"."users" DROP COLUMN "id"',
    ]);
    expect(stmts.every((s) => s.destructive === true)).toBe(true);
  });

  it('自增变更：ADD/DROP IDENTITY；注释变更走 COMMENT ON（置 NULL 删除）', () => {
    const current = baseSpec();
    const noIdentity: TableSpec = {
      ...current,
      columns: current.columns.map((c) => (c.name === 'id' ? { ...c, autoIncrement: false } : c)),
    };
    expect(buildAlterTableStatements('public', 'users', noIdentity, current).map((s) => s.sql)).toEqual([
      'ALTER TABLE "public"."users" ALTER COLUMN "id" DROP IDENTITY IF EXISTS',
    ]);
    const commentChange: TableSpec = {
      ...current,
      columns: current.columns.map((c) => (c.name === 'amount' ? { ...c, comment: '金额' } : c)),
    };
    expect(buildAlterTableStatements('public', 'users', commentChange, current).map((s) => s.sql)).toEqual([
      'COMMENT ON COLUMN "public"."users"."amount" IS \'金额\'',
    ]);
  });
});

describe('库级 DDL（M8-DBDDL / D-19：PG「库」= schema）', () => {
  it('CREATE SCHEMA：标识符双引号引用', () => {
    expect(buildCreateSchemaStatements({ name: 'appdata' })).toEqual([
      { sql: 'CREATE SCHEMA "appdata"' },
    ]);
  });

  it('DROP SCHEMA CASCADE：destructive 标记（连带删表在确认层明示）', () => {
    const stmts = buildDropSchemaStatements('appdata');
    expect(stmts).toEqual([{ sql: 'DROP SCHEMA "appdata" CASCADE', destructive: true }]);
  });

  it('schema 名校验（危险字符黑名单，E_VALIDATION）', () => {
    expect(() => buildCreateSchemaStatements({ name: 'a\nb' })).toThrowError(DriverError);
    expect(() => buildDropSchemaStatements('a"b')).toThrowError(DriverError);
    // 连字符 schema 名合法（回归：test-api 类真实名曾被白名单误拒）
    expect(buildCreateSchemaStatements({ name: 'app-data' })[0].sql).toBe('CREATE SCHEMA "app-data"');
  });
});
