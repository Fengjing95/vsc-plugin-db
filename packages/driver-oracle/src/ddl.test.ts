import { describe, expect, it } from 'vitest';
import {
  buildAlterTableStatements,
  buildCreateTableStatements,
  buildCreateUserStatements,
  buildDropUserStatements,
  escapeDdlLiteral,
  translateOracleType,
} from './ddl';

/** DDL 生成单测（驱动规范 §10 fail-closed / §3 @since v0.1.2；表设计器批次 B 键/外键/索引口径） */
const col = (name: string, dataType: string, extra: Partial<{ nullable: boolean; isPrimaryKey: boolean; autoIncrement: boolean; defaultValue: string; comment: string; ordinal: number }> = {}) => ({
  name,
  dataType,
  nullable: extra.nullable ?? true,
  isPrimaryKey: extra.isPrimaryKey ?? false,
  autoIncrement: extra.autoIncrement,
  defaultValue: extra.defaultValue,
  comment: extra.comment,
  ordinal: extra.ordinal ?? 1,
});

describe('buildCreateTableStatements', () => {
  it('identity 主键 + 默认值 + 注释语句序列', () => {
    const stmts = buildCreateTableStatements('DBKIT', {
      name: 'cf_t',
      comment: '表注释',
      columns: [
        col('id', 'bigint', { nullable: false, isPrimaryKey: true, autoIncrement: true }),
        col('uname', 'varchar(64)', { nullable: false, defaultValue: 'anon', comment: '名称' }),
      ],
    });
    expect(stmts[0].sql).toBe(
      'CREATE TABLE "DBKIT"."cf_t" (\n' +
        '  "id" NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n' +
        '  "uname" VARCHAR2(64 CHAR) DEFAULT \'anon\' NOT NULL,\n' +
        '  PRIMARY KEY ("id")\n' +
        ')',
    );
    expect(stmts.map((s) => s.sql)).toContain('COMMENT ON TABLE "DBKIT"."cf_t" IS \'表注释\'');
    expect(stmts.map((s) => s.sql)).toContain('COMMENT ON COLUMN "DBKIT"."cf_t"."uname" IS \'名称\'');
  });

  it('唯一键/外键内联 CONSTRAINT + 二级索引独立语句', () => {
    const stmts = buildCreateTableStatements('DBKIT', {
      name: 't',
      columns: [
        col('id', 'int', { nullable: false, isPrimaryKey: true }),
        col('uid', 'varchar(64)', { nullable: false }),
        col('ref_id', 'bigint'),
      ],
      uniqueKeys: [{ name: 'uk_uid', columns: ['uid'] }],
      foreignKeys: [{ name: 'fk_ref', columns: ['ref_id'], refTable: 'r', refColumns: ['id'], onDelete: 'CASCADE' }],
      indexes: [{ name: 'idx_pair', columns: ['uid', 'ref_id'] }],
    });
    expect(stmts[0].sql).toContain('CONSTRAINT "uk_uid" UNIQUE ("uid")');
    expect(stmts[0].sql).toContain('CONSTRAINT "fk_ref" FOREIGN KEY ("ref_id") REFERENCES "r" ("id") ON DELETE CASCADE');
    expect(stmts.map((s) => s.sql)).toContain('CREATE INDEX "idx_pair" ON "DBKIT"."t" ("uid", "ref_id")');
  });

  it('ON DELETE NO ACTION 省略子句；ON UPDATE 拒绝（Oracle 无该语法）', () => {
    const mk = (fk: { onDelete?: 'CASCADE' | 'SET NULL' | 'NO ACTION'; onUpdate?: 'CASCADE' }) =>
      buildCreateTableStatements('DBKIT', {
        name: 't',
        columns: [col('id', 'int', { nullable: false, isPrimaryKey: true }), col('r', 'int')],
        foreignKeys: [{ name: 'fk', columns: ['r'], refTable: 'r0', refColumns: ['id'], ...fk }],
      });
    expect(mk({ onDelete: 'NO ACTION' })[0].sql).not.toContain('ON DELETE');
    expect(() => mk({ onDelete: 'CASCADE', onUpdate: 'CASCADE' })).toThrow(/ON UPDATE/);
    expect(() => mk({ onDelete: 'RESTRICT' as never })).toThrow(/CASCADE\/SET NULL/);
  });

  it('fail-closed：非法标识符 / 空列集 / 多自增 / 自增非主键；空串默认值 = 无默认（§3 口径）', () => {
    const base = { name: 't', columns: [col('id', 'int', { nullable: false, isPrimaryKey: true })] };
    expect(() => buildCreateTableStatements('DBKIT', { ...base, name: 't"x' })).toThrow(/非法字符/);
    expect(() => buildCreateTableStatements('DBKIT', { ...base, name: 't\nx' })).toThrow(/非法字符/);
    expect(() => buildCreateTableStatements('DBKIT', { ...base, columns: [] })).toThrow(/至少需要一列/);
    expect(() =>
      buildCreateTableStatements('DBKIT', {
        ...base,
        columns: [
          col('a', 'int', { isPrimaryKey: true, autoIncrement: true }),
          col('b', 'int', { isPrimaryKey: true, autoIncrement: true }),
        ],
      }),
    ).toThrow(/只允许一个自增列/);
    expect(() =>
      buildCreateTableStatements('DBKIT', { ...base, columns: [col('id', 'int'), col('n', 'int', { autoIncrement: true })] }),
    ).toThrow(/自增但不是主键/);
    // defaultValue '' = 无默认值（驱动规范 §3 ColumnSpec 契约）——不产生 DEFAULT 子句
    const stmts = buildCreateTableStatements('DBKIT', {
      ...base,
      columns: [col('id', 'int', { nullable: false, isPrimaryKey: true, defaultValue: '' })],
    });
    expect(stmts[0].sql).not.toContain('DEFAULT');
  });

  it('默认值字面量：数值/函数/日期关键字原样、字符串补引号转义', () => {
    expect(escapeDdlLiteral('42')).toBe('42');
    expect(escapeDdlLiteral('SYSDATE')).toBe('SYSDATE');
    expect(escapeDdlLiteral('CURRENT_TIMESTAMP')).toBe('CURRENT_TIMESTAMP');
    expect(escapeDdlLiteral("it's")).toBe("'it''s'");
  });
});

describe('buildAlterTableStatements（两半段顺序 + 红线）', () => {
  const current = {
    name: 't',
    comment: 'old',
    columns: [
      col('id', 'NUMBER(10, 0)', { nullable: false, isPrimaryKey: true, ordinal: 1 }),
      col('uname', 'VARCHAR2(64 CHAR)', { nullable: false, ordinal: 2 }),
      col('dropme', 'NUMBER(9)', { nullable: true, ordinal: 3 }),
    ],
    uniqueKeys: [{ name: 'uk_old', columns: ['uname'] }],
    foreignKeys: [{ name: 'fk_old', columns: ['uname'], refTable: 'r', refColumns: ['id'] }],
    indexes: [{ name: 'idx_old', columns: ['uname'] }],
  };

  it('删列 + 其上的约束/索引：DROP 语句先于列删除（外键→唯一键→索引→列）', () => {
    // dropme 上的依赖约束/索引与列一并移除（P-57②：Oracle 对被依赖列拒绝 DROP COLUMN）
    const target = {
      ...current,
      columns: current.columns.filter((c) => c.name !== 'dropme'),
      uniqueKeys: [],
      foreignKeys: [],
      indexes: [],
    };
    const stmts = buildAlterTableStatements('DBKIT', 't', target, current);
    const sqls = stmts.map((s) => s.sql);
    expect(sqls[0]).toBe('ALTER TABLE "DBKIT"."t" DROP CONSTRAINT "fk_old"');
    expect(sqls[1]).toBe('ALTER TABLE "DBKIT"."t" DROP CONSTRAINT "uk_old"');
    expect(sqls[2]).toBe('DROP INDEX "idx_old"');
    expect(sqls[3]).toBe('ALTER TABLE "DBKIT"."t" DROP ("dropme")');
    expect(stmts.find((s) => s.sql.includes('DROP ("dropme")'))?.destructive).toBe(true);
  });

  it('仅删列（无依赖约束）：列删除单句，约束/索引保留', () => {
    const target = { ...current, columns: current.columns.filter((c) => c.name !== 'dropme') };
    const stmts = buildAlterTableStatements('DBKIT', 't', target, current);
    expect(stmts.map((s) => s.sql)).toEqual(['ALTER TABLE "DBKIT"."t" DROP ("dropme")']);
  });

  it('主键变更：DROP PRIMARY KEY → ADD PRIMARY KEY，均标 destructive（删除侧）', () => {
    const target = {
      ...current,
      columns: current.columns.map((c) => (c.name === 'uname' ? { ...c, isPrimaryKey: true } : c)),
    };
    const stmts = buildAlterTableStatements('DBKIT', 't', target, current);
    expect(stmts[0].sql).toBe('ALTER TABLE "DBKIT"."t" DROP PRIMARY KEY');
    expect(stmts[0].destructive).toBe(true);
    expect(stmts.map((s) => s.sql)).toContain('ALTER TABLE "DBKIT"."t" ADD PRIMARY KEY ("id", "uname")');
  });

  it('加列合并单句；改类型标 destructive；类型比较大小写折叠（无假 ALTER）', () => {
    const target = {
      ...current,
      columns: [
        col('id', 'NUMBER(10, 0)', { nullable: false, isPrimaryKey: true, ordinal: 1 }),
        col('uname', 'VARCHAR2(128 CHAR)', { nullable: false, ordinal: 2 }),
        col('extra', 'int', { nullable: true, ordinal: 4 }),
      ],
      uniqueKeys: [],
      foreignKeys: [],
      indexes: [],
    };
    // uname 类型扩宽（64→128）→ MODIFY + destructive；dropme 删；extra 加（int 翻译 NUMBER(10, 0)）
    const target2 = { ...target, columns: target.columns.filter((c) => c.name !== 'dropme') };
    const stmts = buildAlterTableStatements('DBKIT', 't', target2, current);
    const modify = stmts.find((s) => s.sql.includes('MODIFY'));
    expect(modify?.sql).toBe('ALTER TABLE "DBKIT"."t" MODIFY ("uname" VARCHAR2(128 CHAR) NOT NULL)');
    expect(modify?.destructive).toBe(true);
    expect(stmts.map((s) => s.sql)).toContain('ALTER TABLE "DBKIT"."t" ADD ("extra" NUMBER(10, 0) NULL)');

    // 大小写折叠：同类型不同大小写 → 无语句
    const sameCase = buildAlterTableStatements('DBKIT', 't', current, current);
    expect(sameCase.filter((s) => s.sql.includes('MODIFY'))).toHaveLength(0);
  });

  it('无结构差异 → 空数组（红线：基线原样提交零语句）', () => {
    expect(buildAlterTableStatements('DBKIT', 't', current, current)).toHaveLength(0);
  });

  it('IDENTITY 原地增删 → E_UNSUPPORTED；重命名语句在首', () => {
    const target = {
      ...current,
      columns: current.columns.map((c) => (c.name === 'uname' ? { ...c, autoIncrement: true, isPrimaryKey: true } : c)),
    };
    expect(() => buildAlterTableStatements('DBKIT', 't', target, current)).toThrow(/IDENTITY/);

    const renamed = buildAlterTableStatements('DBKIT', 't', { ...current, name: 't2' }, current);
    expect(renamed[0].sql).toBe('ALTER TABLE "DBKIT"."t" RENAME TO "t2"');
  });

  it('注释变更：覆盖与删除（IS NULL）', () => {
    const target = { ...current, comment: 'new' };
    const stmts = buildAlterTableStatements('DBKIT', 't', target, current);
    expect(stmts.map((s) => s.sql)).toContain('COMMENT ON TABLE "DBKIT"."t" IS \'new\'');
    const cleared = buildAlterTableStatements('DBKIT', 't', { ...current, comment: undefined }, current);
    expect(cleared.map((s) => s.sql)).toContain('COMMENT ON TABLE "DBKIT"."t" IS NULL');
  });
});

describe('库级 DDL（CREATE/DROP USER，ADR D-23 岔口 8）', () => {
  it('CREATE USER：密码 quoted + USERS 配额 + 最小授权', () => {
    const stmts = buildCreateUserStatements({ name: 'appdata', password: 's3cret' });
    expect(stmts[0].sql).toBe('CREATE USER "appdata" IDENTIFIED BY "s3cret" DEFAULT TABLESPACE USERS QUOTA UNLIMITED ON USERS');
    expect(stmts[1].sql).toBe('GRANT CREATE SESSION, RESOURCE, CREATE VIEW TO "appdata"');
  });

  it('缺密码/含引号密码 → E_VALIDATION（fail-closed）', () => {
    expect(() => buildCreateUserStatements({ name: 'x' })).toThrow(/密码/);
    expect(() => buildCreateUserStatements({ name: 'x', password: 'a"b' })).toThrow(/密码/);
  });

  it('DROP USER CASCADE 标 destructive；非法标识符拒绝', () => {
    const stmts = buildDropUserStatements('gone');
    expect(stmts[0].sql).toBe('DROP USER "gone" CASCADE');
    expect(stmts[0].destructive).toBe(true);
    expect(() => buildDropUserStatements('a\u0000b')).toThrow(/非法字符/);
  });
});

describe('translateOracleType（契约/编辑器通用类型 → Oracle 原生，别名翻译其余透传）', () => {
  it('整型族与 decimal 翻译', () => {
    expect(translateOracleType('bigint')).toBe('NUMBER(19, 0)');
    expect(translateOracleType('int')).toBe('NUMBER(10, 0)');
    expect(translateOracleType('integer')).toBe('NUMBER(10, 0)');
    expect(translateOracleType('smallint')).toBe('NUMBER(5, 0)');
    expect(translateOracleType('tinyint')).toBe('NUMBER(3, 0)');
    expect(translateOracleType('decimal(12, 2)')).toBe('NUMBER(12, 2)');
    expect(translateOracleType('decimal')).toBe('NUMBER');
    expect(translateOracleType('numeric(9)')).toBe('NUMBER(9, 0)');
  });

  it('字符族 CHAR 语义与 text 翻译', () => {
    expect(translateOracleType('varchar(64)')).toBe('VARCHAR2(64 CHAR)');
    expect(translateOracleType('varchar2(64)')).toBe('VARCHAR2(64 CHAR)');
    expect(translateOracleType('nvarchar(32)')).toBe('NVARCHAR2(32)');
    expect(translateOracleType('char(2)')).toBe('CHAR(2 CHAR)');
    expect(translateOracleType('text')).toBe('CLOB');
  });

  it('Oracle 原生类型原样透传', () => {
    expect(translateOracleType('NUMBER(12, 2)')).toBe('NUMBER(12, 2)');
    expect(translateOracleType('VARCHAR2(64 CHAR)')).toBe('VARCHAR2(64 CHAR)');
    expect(translateOracleType('TIMESTAMP(3)')).toBe('TIMESTAMP(3)');
    expect(translateOracleType('CLOB')).toBe('CLOB');
  });
});
